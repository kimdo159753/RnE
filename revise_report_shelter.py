def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True)
    ap.add_argument("--orig", required=True)
    ap.add_argument("--template", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--fig-dir", default="report_fig")
    args = ap.parse_args()
    img_dir = tempfile.mkdtemp(prefix="hwpx_imgs_")
    c = rb.extract(args.src, img_dir)
    o = rb.extract(args.orig, tempfile.mkdtemp(prefix="hwpx_orig_"))
    c["title"], c["team"] = o["title"], o.get("team", "(팀코드)")
    for k in ("authors", "advisors"):
        if k in o:
            c[k] = o[k]
    # 그림: 캡션은 원래 파일에서, 그림 2·3은 새로 그린 것으로
    figs = {}
    for k, (fn, w, _) in c["figs"].items():
        figs[k] = (fn, w, o["figs"][k][2])
    for k, new in (("f2", "fig1_flow.png"), ("f3", "fig_percentile_shelter.png")):
        shutil.copy(os.path.join(args.fig_dir, new), os.path.join(img_dir, new))
        figs[k] = (new, figs[k][1], figs[k][2])
    figs["f3"] = (figs["f3"][0], 130, "[그림 3] 예측 확률 백분위별 실제 입양률 (시험 구간, 최종 모델)")
    c["figs"] = figs
    # 표 캡션도 양식 복원본에서는 표 안에 들어가 있어 못 읽으므로 원래 파일의 캡션을 쓴다
    for k, (cap, rel, left, rows) in c["tables"].items():
        c["tables"][k] = (cap or o["tables"][k][0], rel, left, rows)
    revise(c)
    assert all(v[0].startswith("표 ") for v in c["tables"].values()), [v[0] for v in c["tables"].values()]
    rb.build(c, img_dir, args.template, args.out)


if __name__ == "__main__":
    main()
