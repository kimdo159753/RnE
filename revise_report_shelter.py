def sub(text, old, new):
    assert old in text, f"바꿀 문장을 못 찾음: {old[:40]}"
    return text.replace(old, new)


def find(body, start):
    hits = [i for i, b in enumerate(body) if b[0] == "P" and b[1].startswith(start)]
    assert len(hits) == 1, f"문단을 하나로 못 찾음: {start} → {hits}"
    return hits[0]


